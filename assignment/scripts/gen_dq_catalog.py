"""Generate include/sql/00_dq_catalog.sql from the Python rule definitions so ETL and ELT use
identical check names, dimensions and severities."""
import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "include"))
from nammamart import dq  # noqa: E402
from nammamart.common import FILES, ORDER_COLS  # noqa: E402

asof = pd.Timestamp("2026-10-02")
E = lambda cols: pd.DataFrame({c: pd.Series([], dtype="object") for c in cols})  # noqa: E731
rows = []
def add(src, res):
    for r in res:
        if r["check_name"].split(".", 1)[1] != "latest_order_not_stale":  # file-level check, handled separately
            rows.append((src, r["check_name"].split(".", 1)[1], r["dimension"], r["severity"]))
add("customers", dq.validate_customers(E(FILES["customers"][1]), "d", "r", asof).results)
add("products", dq.validate_products(E(FILES["products"][1]), "d", "r", asof).results)
add("stores", dq.validate_stores(E(FILES["stores"][1]), "d", "r", asof).results)
prod = pd.DataFrame({"product_id": [], "mrp": []})
for src in ("orders", "orders_increment"):
    add(src, dq.validate_orders(E(ORDER_COLS), src, "d", "r", asof, set(), prod, set()).results)
add("payments", dq.validate_payments(E(FILES["payments"][1]), "d", "r", asof,
                                     pd.Series([], dtype=float), pd.Series([], dtype=object)).results)
lines = ["-- GENERATED by scripts/gen_dq_catalog.py from include/nammamart/dq.py. Do not edit by hand.",
         "CREATE OR REPLACE TABLE dq_check_catalog AS SELECT * FROM (VALUES"]
lines += [",\n".join(f"  ('{a}','{b}','{c}','{d}')" for a, b, c, d in rows)]
lines += [") AS t(src, check_name, dimension, severity);"]
(ROOT / "include" / "sql" / "00_dq_catalog.sql").write_text("\n".join(lines) + "\n")
print(len(rows), "catalog rows")
